"""Independent re-check (structures 27/09) of C1's classification of the pair (y1, y2) in O_24 (conway99-c1
data/finishC/o24_ypairs.json: 141 orbits, 3 302 040 normalised configurations).
Independent: own Golay code (cyclic, generator polynomial g = X^11+X^9+X^7+X^6+X^5+X+1, parity bit 23 = infinity), own M24
generators (each tested on the 4096 words, group order checked by sympy), own orbit count (connected components of the
action graph, scipy).
Normal form (scaled by sqrt8): y1 = 1 - 4 1_{T1} (c1 = 0), y2 = eps_D (1 - 4 1_{T2}), T1 fixed, T2 disjoint 4-set, D in
Golay mod Omega with y1.y2 = 0  <=>  |D & A| = 1 + |D|/4, A = T1 u T2.
Symmetries: Stab_M24(T1) on (T2, [D]); swap (T2, T1, D) mapped back by any h in M24 with h(T2) = T1.
Per orbit: size, |D|, A octad?, number of norm-3 vectors orthogonal to y1 and y2, and whether some norm-3 v has
|(v,y1)| = |(v,y2)| = 3 (C1's trap test for O_24).  Usage: python o24_ypairs_check.py"""
import itertools, json, random, sys, time
import numpy as np

T0 = time.time()
OM = (1 << 24) - 1
wt = lambda x: bin(x).count('1')
g = sum(1 << b for b in (11, 9, 7, 6, 5, 1, 0))
WORDS = []
for m in range(4096):
    w = 0
    for j in range(12):
        if m >> j & 1:
            w ^= g << j
    if wt(w) % 2:
        w |= 1 << 23
    WORDS.append(w)
CODE = set(WORDS)
assert len(CODE) == 4096 and sorted({wt(w) for w in CODE}) == [0, 8, 12, 16, 24]
OCT = [w for w in WORDS if wt(w) == 8]
DOD = [w for w in WORDS if wt(w) == 12]

INF = 23
Q = {(x * x) % 23 for x in range(1, 23)}
inv = lambda x: pow(x, 21, 23)


def perm(f):
    return [f(i) for i in range(24)]


def s_(i):
    return INF if i == INF else (i + 1) % 23


def m_(i):
    return INF if i == INF else (2 * i) % 23


def t_(i):
    if i == INF:
        return 0
    if i == 0:
        return INF
    return (-inv(i)) % 23


def d1(i):
    if i in (0, INF):
        return i
    return (pow(i, 3, 23) * inv(9)) % 23 if i in Q else (9 * pow(i, 3, 23)) % 23


def d2(i):
    if i in (0, INF):
        return i
    return (9 * pow(i, 3, 23)) % 23 if i in Q else (pow(i, 3, 23) * inv(9)) % 23


def apply(p, x):
    y = 0
    while x:
        b = x & -x
        y |= 1 << p[b.bit_length() - 1]
        x ^= b
    return y


def preserves(p):
    return all(apply(p, w) in CODE for w in WORDS)


cands = {'shift': perm(s_), 'times2': perm(m_), 'minus_inv': perm(t_), 'delta1': perm(d1), 'delta2': perm(d2),
         'neg': perm(lambda i: INF if i == INF else (-i) % 23)}
ok = {k: preserves(p) for k, p in cands.items()}
print('automorphisms of this code:', ok, flush=True)
GENS = [cands[k] for k in ('shift', 'times2', 'minus_inv') if ok[k]] + [cands[k] for k in ('delta1', 'delta2') if ok[k]][:1]
from sympy.combinatorics import Permutation, PermutationGroup
order = PermutationGroup([Permutation(p) for p in GENS]).order()
print('group order', order, '(M24 = 244823040)', flush=True)
assert order == 244823040


def compose(p, q):          # first q then p
    return [p[q[i]] for i in range(24)]


def inverse(p):
    r = [0] * 24
    for i, x in enumerate(p):
        r[x] = i
    return r


T1 = 0b1111                      # points 0,1,2,3
# transversal of M24 on 4-sets: for every 4-set X an element mapping X to T1
tree = {T1: list(range(24))}     # X -> element e with e(T1) = X
frontier = [T1]
while frontier:
    nf = []
    for X in frontier:
        for gg in GENS:
            Y = apply(gg, X)
            if Y not in tree:
                tree[Y] = compose(gg, tree[X])
                nf.append(Y)
    frontier = nf
assert len(tree) == 10626
to_T1 = {X: inverse(e) for X, e in tree.items()}      # maps X to T1
# Schreier generators of Stab(T1)
rng = random.Random(3)
keys = list(tree)
SG = []
for _ in range(60):
    X = rng.choice(keys)
    gg = rng.choice(GENS)
    Y = apply(gg, X)
    sgen = compose(to_T1[Y], compose(gg, tree[X]))       # T1 -> X -> Y -> T1
    assert apply(sgen, T1) == T1
    SG.append(sgen)
H = PermutationGroup([Permutation(p) for p in SG])
print('|Stab(T1)| =', H.order(), '(expected 23040)', flush=True)
assert H.order() == 23040
# a small generating set (memory): random triples of Schreier generators until they generate Stab(T1)
while True:
    trial = rng.sample(SG, 3)
    if PermutationGroup([Permutation(p) for p in trial]).order() == 23040:
        SG = trial
        break
print('Stab(T1) generated by', len(SG), 'elements', flush=True)

# configurations
REST = [i for i in range(24) if not T1 >> i & 1]
T2S = [sum(1 << i for i in c) for c in itertools.combinations(REST, 4)]


def canonD(D):
    return min(D, D ^ OM)


keys_list = []
for T2 in T2S:
    A = T1 | T2
    Ds = set()
    for O in OCT:
        if wt(O & A) == 3:
            Ds.add(canonD(O))
    for Dd in DOD:
        if wt(Dd & A) == 4:
            Ds.add(canonD(Dd))
    for D in Ds:
        keys_list.append((T2 << 24) | D)
KEYS = np.array(sorted(keys_list), dtype=np.int64)
N = len(KEYS)
print('normalised configurations:', N, '(C1: 3302040)', flush=True)


def tables(p):
    return [np.array([apply(p, b << (8 * k)) for b in range(256)], dtype=np.int64) for k in range(3)]


def act_masks(tb, m):
    return tb[0][m & 255] | tb[1][(m >> 8) & 255] | tb[2][(m >> 16) & 255]


T2a = KEYS >> 24
Da = KEYS & OM


def canon_vec(D):
    return np.minimum(D, D ^ OM)


MAPS = []
for p in SG:
    tb = tables(p)
    nT2 = act_masks(tb, T2a)
    nD = canon_vec(act_masks(tb, Da))
    idx = np.searchsorted(KEYS, (nT2 << 24) | nD)
    assert (KEYS[idx] == ((nT2 << 24) | nD)).all()
    MAPS.append(idx.astype(np.int32))
# swap: (T2, D) -> h (T2 -> T1): new T2 = h(T1), D -> h(D), h = to_T1[T2]; configs of one T2 are contiguous in KEYS
nT2 = np.empty(N, dtype=np.int64)
nD = np.empty(N, dtype=np.int64)
bounds = np.searchsorted(KEYS, np.array([T2 << 24 for T2 in sorted(T2S)] + [1 << 48], dtype=np.int64))
for k, T2 in enumerate(sorted(T2S)):
    lo, hi = bounds[k], bounds[k + 1]
    tb = tables(to_T1[T2])
    nT2[lo:hi] = act_masks(tb, np.array([T1], dtype=np.int64))[0]
    nD[lo:hi] = canon_vec(act_masks(tb, Da[lo:hi]))
idx = np.searchsorted(KEYS, (nT2 << 24) | nD)
assert (KEYS[idx] == ((nT2 << 24) | nD)).all()
MAPS.append(idx.astype(np.int32))
del nT2, nD, idx
INV = []
for f in MAPS[:-1]:                          # Stab(T1) elements act bijectively on the configurations
    fi = np.empty_like(f)
    fi[f] = np.arange(N, dtype=np.int32)
    assert len(np.unique(f)) == N
    INV.append(fi)
SW = MAPS[-1]                                # swap edges x -- SW[x] (a relation: h is a chosen section)
lab = np.arange(N, dtype=np.int32)
for it in range(200):
    old = lab.copy()
    for f, fi in zip(MAPS[:-1], INV):
        lab = np.minimum(lab, np.minimum(lab[f], lab[fi]))
    lab = np.minimum(lab, lab[SW])
    np.minimum.at(lab, SW, lab.copy())
    for _ in range(5):
        lab = lab[lab]
    if (lab == old).all():
        break
roots_, lab = np.unique(lab, return_inverse=True)
nc = len(roots_)
print('ORBITS:', nc, '(C1: 141), label passes', it + 1, '  %.0fs' % (time.time() - T0), flush=True)

# per-orbit invariants
sizes = np.bincount(lab)
_, firsti = np.unique(lab, return_index=True)
first = {l: int(i) for l, i in enumerate(firsti)}
SIGNS = []
for W in WORDS:
    SIGNS.append(np.array([-1 if W >> i & 1 else 1 for i in range(24)], dtype=np.int64))
SIGNS = np.array(SIGNS)
OCTSET = set(OCT)
res = []
for l, i in sorted(first.items()):
    T2, D = int(KEYS[i] >> 24), int(KEYS[i] & OM)
    y1 = np.array([-3 if T1 >> k & 1 else 1 for k in range(24)])
    eps = np.array([-1 if D >> k & 1 else 1 for k in range(24)])
    y2 = eps * np.array([-3 if T2 >> k & 1 else 1 for k in range(24)])
    assert int(y1 @ y2) == 0
    p1, p2 = SIGNS @ y1, SIGNS @ y2
    n_perp = int(((p1 == 0) & (p2 == 0)).sum())
    trap = bool(((np.abs(p1) == 24) & (np.abs(p2) == 24)).any())     # (v,y) = 3 <=> E.a = 24 (scaled by 8)
    res.append({'size': int(sizes[l]), 'D_weight': min(wt(D), 24 - wt(D)), 'A_octad': (T1 | T2) in OCTSET,
                'n_norm3_perp': n_perp, 'trap_vector': trap})
print('orbit size sum', int(sizes.sum()))
import collections
print(collections.Counter((r['D_weight'], r['A_octad'], r['trap_vector']) for r in res))
c1 = json.load(open('C:/home/researcher/Desktop/c1_recherche/data/finishC/o24_ypairs.json'))['orbits']
mine = sorted((r['size'], r['D_weight'], r['A_octad'], r['n_norm3_perp']) for r in res)
theirs = sorted((o['normalised_configs'], o['D_weight'], o['A_is_octad'], o['n_norm3_perp']) for o in c1)
print('multiset of (orbit size, |D|, A octad, #norm3 perp) identical to C1:', mine == theirs)
if mine != theirs:
    print('mine-only', sorted(set(mine) - set(theirs))[:10]); print('theirs-only', sorted(set(theirs) - set(mine))[:10])
json.dump(res, open('o24_ypairs_check.json', 'w'))
print('done %.0fs' % (time.time() - T0))
